/**
 * Get the Easy German video assigned to a specific course day.
 * If the day is > 64, wraps around gracefully.
 */
export function getEasyGermanVideoForDay(dayNumber: number): EasyGermanLessonVideo {
  if (!dayNumber || dayNumber < 1) return EASY_GERMAN_A1_VIDEOS[0];
  const idx = (dayNumber - 1) % EASY_GERMAN_A1_VIDEOS.length;
  return EASY_GERMAN_A1_VIDEOS[idx];
}

/**
 * Storage helpers for tracking completed Easy German videos
 */
export function isEasyGermanVideoWatched(dayNumber: number): boolean {
  try {
    return localStorage.getItem(`easy_german_watched_day_${dayNumber}`) === 'true';
  } catch {
    return false;
  }
}

export function setEasyGermanVideoWatched(dayNumber: number, watched: boolean): void {
  try {
    const key = `easy_german_watched_day_${dayNumber}`;
    if (watched) {
      localStorage.setItem(key, 'true');
    } else {
      localStorage.removeItem(key);
    }
  } catch (e) {
    console.warn('Could not save Easy German watched state:', e);
  }
}
